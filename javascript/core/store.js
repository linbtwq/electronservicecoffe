// ============================================================
// javascript/core/store.js
//
// назначение
// простейший стейт-менеджер для заказа пополнения.
//
// ответственность
// - хранить состояние текущего заказа (точка, количества, позиции)
// - отдавать живую ссылку на объект заказа
// - сбрасывать заказ
//
// про идентичность объекта
// state.order создаётся один раз при загрузке модуля
// и никогда не пересоздаётся.
//
// resetOrder только обнуляет поля у того же объекта.
// getOrder возвращает живую ссылку, а не копию.
//
// это важно потому что внешний код (assortments.js)
// держит `const order = appStore.getOrder()`
// и мутирует поля напрямую: order.qty[code] = 5.
// Если getOrder начнёт возвращать копию,
// все мутации уйдут в никуда и заказ перестанет работать.
//
// если однажды понадобится иммутабельный подход,
// getOrder должен вернуть копию,
// а все мутации должны идти только через методы
// setOrder / setQty / resetOrder.
// сейчас этого нет: заказ живёт только в assortments.js.
// ============================================================

const appStore = (function () {
    // единственный экземпляр объекта заказа.
    // не пересоздаётся никогда.
    const order = {
        pointId: null,
        qty: {},
        items: {},
        requestId: null,
        canOrder: false
    };

    return {
        // возвращает живую ссылку на объект заказа, не копию.
        // внешний код имеет право мутировать поля напрямую.
        getOrder() {
            return order;
        },

        // обнуляет поля существующего объекта.
        // объект не пересоздаётся, внешние ссылки остаются валидными.
        resetOrder() {
            order.pointId = null;
            order.qty = {};
            order.items = {};
            order.requestId = null;
            order.canOrder = false;
        },

        // мержит поля в существующий объект.
        // используется когда нужно обновить часть полей разом.
        setOrder(partial) {
            Object.assign(order, partial);
        },

        // обновляет количество одной позиции.
        // qty > 0 записывает, иначе удаляет ключ.
        setQty(code, qty) {
            if (qty > 0) order.qty[code] = qty;
            else delete order.qty[code];
            order.requestId = null;
        }
    };
})();