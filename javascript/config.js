// адрес сервиса по умолчанию
// используется если пользователь не переопределил его в браузере
const _RAW_API_BASE_DEFAULT = 'https://api.coffeemeters.pp.ua/siteapinew/hs/siteapi';

// выбирает адрес сервиса для текущего запуска
// порядок такой
// первое смотрим есть ли в localStorage ключ apiBaseOverride
// второе проверяем что значение похоже на http или https ссылку
// третье если проверка не прошла возвращаем адрес по умолчанию
// это позволяет проверять сборку на другом сервере без правки исходников
function resolveApiBase() {
    try {
        const override = localStorage.getItem('apiBaseOverride');
        // пустые строки и посторонние значения игнорируем
        if (override && /^https?:\/\/.+/i.test(override)) {
            // убираем завершающие слеши перед сборкой адресов запросов
            return override.replace(/\/+$/, '');
        }
    } catch (e) {}
    return _RAW_API_BASE_DEFAULT;
}

// адрес который реально используется в этой сессии
const _RAW_API_BASE = resolveApiBase();

// основной объект настроек
// читается всеми модулями через имя APP_CONFIG
const APP_CONFIG = {
    // адрес сервиса без завершающего слеша
    // завершающий слеш убирает уже core/state.js при первом чтении
    apiBase: _RAW_API_BASE,

    // версия api которую ждёт сервис 1с
    apiVersion: '1.0',

    // предел ожидания сетевых запросов в миллисекундах
    // чтение справочников быстрее, отправка документов дольше
    loadTimeoutMs: 10000,
    sendTimeoutMs: 20000,

    // начальная пауза перед повторной отправкой очереди
    // дальше интервал растёт по экспоненте в scheduleSyncRetry
    syncRetrySeconds: 30,

    // срок блокировки точки после отправки показаний
    // режим endOfDay снимает блокировку в полночь
    // режим hours использует значение lockHours
    lockMode: 'endOfDay',
    lockHours: 12,

    // автоматический выход после успешной отправки показаний
    // выключено по умолчанию
    autoLogoutAfterSubmit: false,

    // сколько карточек показывать за одну порцию рендера
    // на слабых устройствах script.js уменьшит это значение
    pageSize: 30,

    // через сколько минут считать данные устаревшими
    // при возврате на вкладку script.js может перезагрузить данные
    refreshAfterMinutes: 5
};

// задаёт совместимую версию api если значение не указано
// нужно чтобы код на сервере не получал пустой параметр v
if (!APP_CONFIG.apiVersion) APP_CONFIG.apiVersion = '1.0';